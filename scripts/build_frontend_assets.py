#!/usr/bin/env python3
"""Build the single small render-blocking stylesheet used by every page.

Keeping source stylesheets modular makes maintenance pleasant; concatenating the
critical set avoids seven serial CSS requests before first paint.  Third-party
icon styles deliberately remain separate and are loaded non-blocking by the
base template because the page is fully usable before decorative glyphs arrive.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSS_DIR = ROOT / "static" / "css"
OUTPUT = CSS_DIR / "site.css"
SOURCES = (
    "fonts.css",
    "css.css",
    "header.css",
    "header-fix.css",
    "_main.css",
    "_category.css",
    "cart_actions.css",
    "_ppr.css",
)


def main() -> None:
    chunks = ["/* Generated by scripts/build_frontend_assets.py. Do not edit directly. */\n"]
    for name in SOURCES:
        source = CSS_DIR / name
        chunks.append(f"\n/* ===== {name} ===== */\n")
        chunks.append(source.read_text(encoding="utf-8").rstrip())
        chunks.append("\n")
    OUTPUT.write_text("".join(chunks), encoding="utf-8")
    print(f"Built {OUTPUT.relative_to(ROOT)} from {len(SOURCES)} source files.")


if __name__ == "__main__":
    main()
